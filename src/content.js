export const challengeIds = ["order", "sort", "size"];
export function cleanSave(raw) {
  const o = raw && typeof raw === "object" ? raw : {};
  const unique = (v, valid) => [
    ...new Set(Array.isArray(v) ? v.filter(valid) : []),
  ];
  return {
    done: unique(o.done, (x) => destinations.some((d) => d.id === x)),
    signals: unique(o.signals, (x) => Number.isInteger(x) && x >= 0 && x < 8),
    challenges: unique(o.challenges, (x) => challengeIds.includes(x)),
  };
}
export function reward(state, type, id) {
  const next = cleanSave(state);
  if (type in next) next[type].push(id);
  return cleanSave(next);
}
export function score(s) {
  const v = cleanSave(s);
  return v.done.length * 100 + v.signals.length * 10 + v.challenges.length * 50;
}
export function phaseForDay(day) {
  return Math.round(((((day % 30) + 30) % 30) / 30) * 8) % 8;
}
export function lit(phase, x, y) {
  return (
    x * x + y * y <= 1 &&
    x * Math.sin((phase * Math.PI) / 4) -
      Math.sqrt(Math.max(0, 1 - x * x - y * y)) *
        Math.cos((phase * Math.PI) / 4) >
      0
  );
}
